import SwiftUI

enum AppColors {
    static let backgroundPrimary = Color("BackgroundPrimary")
    static let fieldBackground = Color("SurfaceSecondary")
    static let actionBackground = Color.accentColor
    static let border = Color("Border")
    static let textPrimary = Color("TextPrimary")
    static let textSecondary = Color("TextSecondary")

    static let surfaceSecondary = fieldBackground
    static let accent = actionBackground
    static let error = border
    static let success = border
}
